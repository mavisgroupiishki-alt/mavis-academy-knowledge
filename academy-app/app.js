function repoLink(path) {
  return REPO + path.split('/').map(encodeURIComponent).join('/');
}
function uid(courseId, dayIndex) {
  return `${courseId}:${dayIndex}`;
}
function isDone(courseId, dayIndex) {
  return !!state.completed[uid(courseId, dayIndex)];
}
function courseProgress(courseId) {
  const days = academy[courseId].days.length;
  const done = academy[courseId].days.filter((_, i) => isDone(courseId, i)).length;
  return { done, days, pct: Math.round(done / days * 100) };
}
function totalHours(courseId) {
  return academy[courseId].days.length * 2;
}
function setView(view) {
  state.activeView = view;
  document.querySelectorAll('.menu-item').forEach(btn => btn.classList.toggle('active', btn.dataset.view === view));
  persist();
  render();
  window.scrollTo(0,0);
}
function openCourse(courseId) {
  state.activeCourse = courseId;
  setView(courseId);
}
function openDay(courseId, dayIndex) {
  state.activeCourse = courseId;
  state.activeDay = dayIndex;
  state.activeView = `${courseId}-day`;
  persist();
  render();
  window.scrollTo(0,0);
}
