function renderQuiz(courseId, dayIndex, items, answers) {
  return items.map((q, qi) => `
    <div class="question">
      <h4>${qi + 1}. ${esc(q.q)}</h4>
      ${q.opts.map((opt, oi) => {
        const selected = answers[qi] === oi;
        let cls = 'option';
        if (selected) cls += ' selected';
        return `<button class="${cls}" onclick="pickAnswer('${courseId}', ${dayIndex}, ${qi}, ${oi})">${String.fromCharCode(1040 + oi)}. ${esc(opt)}</button>`;
      }).join('')}
      ${answers[qi] !== undefined ? `<div class="notice" style="margin-top:8px">${answers[qi] === q.correct ? '✓ Верно.' : '✦ Обрати внимание.'} ${q.explanation}</div>` : ''}
    </div>
  `).join('');
}

function pickAnswer(courseId, dayIndex, questionIndex, optionIndex) {
  const key = uid(courseId, dayIndex);
  const arr = state.answers[key] ? [...state.answers[key]] : [];
  arr[questionIndex] = optionIndex;
  state.answers[key] = arr;
  persist();
  render();
}

function finishQuiz(courseId, dayIndex) {
  const day = academy[courseId].days[dayIndex];
  const key = uid(courseId, dayIndex);
  const answers = state.answers[key] || [];
  if (answers.length !== day.quiz.length) {
    alert('Нужно ответить на все вопросы теста.');
    return;
  }
  const correct = day.quiz.reduce((acc, q, idx) => acc + ((answers[idx] === q.correct) ? 1 : 0), 0);
  state.completed[key] = true;
  persist();
  alert(`Готово! Результат: ${correct} из ${day.quiz.length}. ${correct >= 4 ? 'День зачтён хорошо.' : 'День зачтён, но рекомендую повторить материал.'}`);
  render();
}

