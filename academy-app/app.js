function render() {
  const view = state.activeView;
  if (view === 'dashboard') {
    crumb.textContent = 'Главная';
    pageTitle.textContent = 'Корпоративное обучение Mavis';
    content.innerHTML = dashboardView();
    return;
  }
  if (view === 'knowledge') {
    crumb.textContent = 'База знаний';
    pageTitle.textContent = 'Obsidian / GitHub';
    content.innerHTML = knowledgeView();
    return;
  }
  if (view === 'sales' || view === 'expert' || view === 'bitrix') {
    crumb.textContent = 'Курсы';
    pageTitle.textContent = academy[view].title;
    content.innerHTML = courseView(view);
    return;
  }
  if (view.endsWith('-day')) {
    const courseId = state.activeCourse;
    crumb.textContent = `${academy[courseId].title} · день`;
    pageTitle.textContent = academy[courseId].days[state.activeDay].title;
    content.innerHTML = dayView(courseId, state.activeDay);
    return;
  }
}

